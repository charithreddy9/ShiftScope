"""Write transparent numerical experiment results and PNG charts."""
import csv,json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

def write_csv(path,rows):
    with open(path,"w",newline="",encoding="utf-8") as f:
        writer=csv.DictWriter(f,fieldnames=rows[0].keys())
        writer.writeheader();writer.writerows(rows)

def summarize(rows):
    groups={}
    for row in rows:
        groups.setdefault((row["model"],row["sigma"],row["method"]),[]).append(row)
    out=[]
    metrics=["accuracy","ece","nll","brier","aurc","mean_confidence","conformal_coverage","conformal_set_size"]
    for (model,sigma,method),items in sorted(groups.items()):
        record=dict(model=model,sigma=sigma,method=method,seeds=len(items))
        for metric in metrics:
            values=np.array([r[metric] for r in items])
            record[metric+"_mean"]=float(values.mean())
            record[metric+"_sd"]=float(values.std(ddof=1)) if len(values)>1 else 0.
        out.append(record)
    return out

def render_chart(summaries,metric,filename,out,guide=None):
    fig,ax=plt.subplots(figsize=(8.5,5))
    for model in sorted({r["model"] for r in summaries}):
        for method in sorted({r["method"] for r in summaries}):
            entries=sorted((r for r in summaries if r["model"]==model and r["method"]==method),key=lambda r:r["sigma"])
            if not entries:continue
            ax.errorbar([r["sigma"] for r in entries],[r[metric+"_mean"] for r in entries],
                yerr=[r[metric+"_sd"] for r in entries],marker="o",capsize=3,label=f"{model.replace('_',' ')} — {method.replace('_',' ')}")
    if guide is not None:ax.axhline(guide,linestyle="--",label="Nominal clean-data target")
    ax.set_xlabel("Gaussian test-only noise (sigma)");ax.set_ylabel(metric.replace("_"," ").title())
    ax.set_title("ShiftScope: uncertainty under synthetic distribution shift")
    ax.legend(fontsize=8);ax.grid(alpha=.2)
    fig.tight_layout();fig.savefig(out/filename,dpi=140);plt.close(fig)

def write_results(rows,folder,seeds,sigmas):
    dest=Path(folder);figs=dest/"figures";figs.mkdir(parents=True,exist_ok=True)
    summary=summarize(rows)
    write_csv(dest/"metrics.csv",rows);write_csv(dest/"summary.csv",summary)
    (dest/"config.json").write_text(json.dumps({"seeds":list(seeds),"sigmas":list(sigmas),"dataset":"sklearn digits","model_count":2,"calibration":"disjoint temperature and conformal subsets"},indent=2)+"\n")
    render_chart(summary,"accuracy","accuracy_vs_shift.png",figs)
    render_chart(summary,"ece","ece_vs_shift.png",figs)
    render_chart(summary,"aurc","aurc_vs_shift.png",figs)
    conformal=[r for r in summary if r["method"]=="temperature_scaled"]
    render_chart(conformal,"conformal_coverage","conformal_coverage.png",figs,guide=.9)
    lines=["# Experiment report","",
    "This report was generated by the experiment runner, using the scikit-learn digits dataset and synthetic noise.","",
    "The conformal 90% marginal coverage guarantee assumes exchangeable calibration and test data; corrupting test images violates this assumption.","",
    "| Model | Noise | Accuracy | ECE (temperature) | Conformal coverage |",
    "| --- | ---: | ---: | ---: | ---: |"]
    for row in conformal:
        lines.append(f"| {row['model'].replace('_',' ')} | {row['sigma']:.1f} | {row['accuracy_mean']:.3f} | {row['ece_mean']:.3f} | {row['conformal_coverage_mean']:.3f} |")
    lines+=["","## Visualizations","","![Accuracy](figures/accuracy_vs_shift.png)","","![Calibration](figures/ece_vs_shift.png)","","![Coverage](figures/conformal_coverage.png)","","![Selective risk](figures/aurc_vs_shift.png)","","Mean and sample standard deviation across random seeds are recorded in summary.csv. This is a small synthetic-shift study, not evidence of real-world deployment reliability."]
    (dest/"report.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    return summary
